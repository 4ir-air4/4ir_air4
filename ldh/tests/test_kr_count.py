"""kr_count()의 만·억 표기와 경계값 점검. 실행: python -m ldh.tests.test_kr_count"""
from ldh.core.data import kr_count

CASES = [
    (0, "0"), (9_999, "9,999"),
    (9_999.6, "1만"), (10_000, "1만"),  # 반올림하면 1만이 되는 값
    (23_456, "2.3만"), (50_000, "5만"), (999_960, "100만"),  # 100만 미만은 소수 한 자리
    (6_280_000, "628만"), (86_040_000, "8,604만"),
    (99_994_999, "9,999만"), (99_995_000, "1억"), (100_000_000, "1억"),  # '10,000만'이 나오면 안 된다
    (4_268_984_000, "42.7억"),
    (-23_456, "-2.3만"),
]

if __name__ == "__main__":
    wrong = [(n, kr_count(n), want) for n, want in CASES if kr_count(n) != want]
    assert not wrong, f"(입력, 결과, 기대): {wrong}"
    print("kr_count 점검 통과")
